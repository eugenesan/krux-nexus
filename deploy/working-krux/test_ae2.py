import sensor, time
sensor.reset()
sensor.set_pixformat(sensor.RGB565)
sensor.set_framesize(sensor.QVGA)
sensor.run(1)
time.sleep(1)
img = sensor.snapshot()
s = img.get_statistics()
print("baseline:", s.l_mean())
sensor.set_exposure(2000)
time.sleep(1)
img = sensor.snapshot()
s = img.get_statistics()
print("exposed:", s.l_mean())
sensor.run(0)
print("done")
