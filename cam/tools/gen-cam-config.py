#!/usr/bin/env python3
"""Generate standalone/cam/cam_config.h from the captured camera uploads.

The captures are the bytes the vendor camera HAL uploaded to the ISP
(VIDIOC_MSM_VFE_REG_CFG) and to the CPP (VIDIOC_MSM_CPP_CFG), taken
from the ROM's own camera stack running on our kernel.  See
standalone/cam/data/README.md.

Input:  a directory with the captured files
        isp_cfg_<n>_n<blocks>_l<len>.bin   -- the ISP uploads
        cpp_cfg_<n>_len<words>.bin        -- the chromatrix message
Output: standalone/cam/cam_config.h

Usage:  tools/gen-cam-config.py <capture-dir> <output.h>
        tools/gen-cam-config.py --list <capture-dir>
"""
import os
import struct
import sys


def parse_name(name):
    """isp_cfg_12_n3_l88.bin -> (12, 3, 88);  cpp_cfg_3_len266.bin -> None"""
    if name.startswith("isp_cfg_"):
        try:
            rest = name[len("isp_cfg_"):-len(".bin")]
            idx, n, l = rest.split("_")
            return int(idx), int(n[1:]), int(l[1:])
        except ValueError:
            return None
    return None


def read_uploads(d):
    """[(index, num_cfg, cmd_len, blocks, data)] sorted by index"""
    out = []
    for name in sorted(os.listdir(d)):
        p = parse_name(name)
        if not p:
            continue
        idx, n, l = p
        raw = open(os.path.join(d, name), "rb").read()
        if len(raw) != n * 16 + l:
            continue
        blocks = raw[:n * 16]
        data = raw[n * 16:]
        out.append((idx, n, l, blocks, data))
    out.sort(key=lambda x: x[0])
    return out


def c_bytes(name, data, per_line=16):
    # NOT const: the driver copies the data blob back to the caller's
    # buffer (copy_to_user at the end of msm_isp_proc_cmd), so the buffer
    # has to be writable -- a .rodata array would fail with EFAULT.
    s = "static unsigned char %s[%d] = {\n" % (name, len(data))
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        s += "\t" + "".join("0x%02x, " % b for b in chunk) + "\n"
    s += "};\n"
    return s


def emit(uploads, cycle, chromatrix, out_path):
    o = []
    o.append("/*\n"
             " * cam_config.h -- GENERATED by tools/gen-cam-config.py.  Do not edit.\n"
             " *\n"
             " * The camera configuration the vendor HAL uploads to the ISP and the\n"
             " * CPP, captured on 2026-10-19 from the ROM's camera stack running on\n"
             " * our own kernel.  These are data, not code: our imaging server\n"
             " * sends them back to the driver, so the vendor HAL and the vendor\n"
             " * blob are not needed at run time.\n"
             " *\n"
             " * %d ISP uploads in the session's initial configuration, and one\n"
             " * period of the per-frame cycle.\n"
             " */\n" % len(uploads))
    o.append("#ifndef CAM_CONFIG_H\n#define CAM_CONFIG_H\n\n")
    o.append("struct cam_upload {\n"
             "\tunsigned short num_cfg;\n"
             "\tunsigned short cmd_len;\n"
             "\tunsigned char *blocks;\t/* num_cfg * 16 bytes */\n"
             "\tunsigned char *data;\t/* cmd_len bytes */\n"
             "};\n\n")

    names = []
    for i, (idx, n, l, blocks, data) in enumerate(uploads):
        bn = "cam_blk_%d" % i
        dn = "cam_dat_%d" % i
        names.append((bn, dn, n, l))
        o.append(c_bytes(bn, blocks))
        o.append(c_bytes(dn, data))
    o.append("\n/* the session's initial configuration, in the order the HAL sent it */\n")
    o.append("static const struct cam_upload cam_initial[] = {\n")
    for i, (idx, n, l, blocks, data) in enumerate(uploads):
        o.append("\t{ %d, %d, cam_blk_%d, cam_dat_%d },\t/* capture %d */\n"
                 % (n, l, i, i, idx))
    o.append("};\n")
    o.append("#define CAM_INITIAL_COUNT %d\n\n" % len(uploads))

    if cycle:
        base = len(uploads)
        for i, (idx, n, l, blocks, data) in enumerate(cycle):
            o.append(c_bytes("cam_cyc_blk_%d" % i, blocks))
            o.append(c_bytes("cam_cyc_dat_%d" % i, data))
        o.append("\n/* one period of the per-frame cycle */\n")
        o.append("static const struct cam_upload cam_cycle[] = {\n")
        for i, (idx, n, l, blocks, data) in enumerate(cycle):
            o.append("\t{ %d, %d, cam_cyc_blk_%d, cam_cyc_dat_%d },\t/* capture %d */\n"
                     % (n, l, i, i, idx))
        o.append("};\n")
        o.append("#define CAM_CYCLE_COUNT %d\n\n" % len(cycle))

    if chromatrix:
        o.append(c_bytes("cam_chromatrix", chromatrix))
        o.append("#define CAM_CHROMATRIX_WORDS %d\n\n"
                 % (len(chromatrix) // 4))

    o.append("#endif /* CAM_CONFIG_H */\n")
    open(out_path, "w").write("".join(o))
    print("wrote %s: %d initial uploads, %d cycle uploads" %
          (out_path, len(uploads), len(cycle) if cycle else 0))


def main():
    if len(sys.argv) < 5:
        print(__doc__)
        return 1
    init_dir, cycle_dir, chroma_file, out_path = sys.argv[1:5]
    uploads = read_uploads(init_dir)
    cycle = read_uploads(cycle_dir)
    chromatrix = None
    if os.path.exists(chroma_file):
        chromatrix = open(chroma_file, "rb").read()
    emit(uploads, cycle, chromatrix, out_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
