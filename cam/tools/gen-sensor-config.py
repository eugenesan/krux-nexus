#!/usr/bin/env python3
"""Generate standalone/cam/sensor_config.h from the captured sensor writes.

The captures are the register arrays the vendor camera HAL writes to the
IMX179 with CFG_WRITE_I2C_ARRAY, taken on 2026-10-19 from the ROM's own
camera stack running on our kernel (see standalone/cam/data/README.md).

Input:  a directory with sensor_cfg_<n>_n<count>.bin files (each entry
        is { uint16 addr; uint16 data; uint32 delay; })
Output: standalone/cam/sensor_config.h

Usage:  tools/gen-sensor-config.py <capture-dir> <output.h>
"""
import glob
import os
import re
import struct
import sys


def c_bytes(name, data, per_line=12):
    s = "static unsigned char %s[%d] = {\n" % (name, len(data))
    for i in range(0, len(data), per_line):
        chunk = data[i:i + per_line]
        s += "\t" + "".join("0x%02x, " % b for b in chunk) + "\n"
    s += "};\n"
    return s


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    d, out_path = sys.argv[1], sys.argv[2]

    files = sorted(glob.glob(os.path.join(d, "sensor_cfg_*.bin")),
                   key=lambda f: int(re.search(r"_(\d+)_", os.path.basename(f)).group(1)))
    uploads = []
    for f in files:
        raw = open(f, "rb").read()
        n = len(raw) // 8
        if n == 0:
            continue
        uploads.append((int(re.search(r"_(\d+)_", os.path.basename(f)).group(1)),
                        n, raw))

    o = []
    o.append("/*\n"
             " * sensor_config.h -- GENERATED by tools/gen-sensor-config.py.\n"
             " * Do not edit.\n"
             " *\n"
             " * The register arrays the vendor camera HAL writes to the IMX179,\n"
             " * in the order it writes them, captured on 2026-10-19 from the\n"
             " * ROM's camera stack running on our own kernel.  They are data,\n"
             " * not code -- our imaging server sends them with\n"
             " * CFG_WRITE_I2C_ARRAY, exactly as the HAL does.\n"
             " *\n"
             " * %d arrays.\n"
             " */\n" % len(uploads))
    o.append("#ifndef SENSOR_CONFIG_H\n#define SENSOR_CONFIG_H\n\n")
    o.append("struct sensor_write {\n"
             "\tunsigned short count;\t\t/* how many registers */\n"
             "\tunsigned char *regs;\t\t/* count * 8 bytes: addr, data, delay */\n"
             "};\n\n")
    for i, (idx, n, raw) in enumerate(uploads):
        o.append(c_bytes("sensor_regs_%d" % i, raw))
    o.append("\n/* the vendor's sequence, in the order it was captured */\n")
    o.append("static const struct sensor_write sensor_sequence[] = {\n")
    for i, (idx, n, raw) in enumerate(uploads):
        o.append("\t{ %d, sensor_regs_%d },\t/* capture %d */\n" % (n, i, idx))
    o.append("};\n")
    o.append("#define SENSOR_SEQUENCE_COUNT %d\n\n" % len(uploads))
    o.append("#endif /* SENSOR_CONFIG_H */\n")
    open(out_path, "w").write("".join(o))
    print("wrote %s: %d arrays" % (out_path, len(uploads)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
