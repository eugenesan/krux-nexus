#!/usr/bin/env python3
"""Generate standalone/cam/imx179_regs.h from the extracted sensor library.

The IMX179's register settings are not in any kernel tree for this device
(neither ours nor the AOSP hammerhead tree has them: the sensor driver is
a stub with only the power sequence).  They live in the vendor's sensor
library, /vendor/lib/libmmcamera_imx179.so, as

    struct msm_camera_i2c_reg_array { uint16 reg_addr; uint16 reg_data; uint32 delay; }

which is exactly the layout the kernel's CFG_WRITE_I2C_ARRAY ioctl
expects (include/media/msm_cam_sensor.h).  This script lifts the arrays
out of that library and writes them as C, so that our imaging server can
program the sensor without any vendor code at runtime.

The arrays are found through the library's own msm_camera_i2c_reg_setting
structures, which hold { pointer, count, addr_type, data_type } -- so the
count comes from the library and not from a heuristic.

Run:  python3 tools/gen-imx179-regs.py <libmmcamera_imx179.so> <out.h>
"""
import struct
import sys

# msm_camera_i2c_reg_addr_type / msm_camera_i2c_data_type (msm_cam_sensor.h)
ADDR_WORD = 2
DATA_BYTE = 1


def segments(d):
    """The ELF's LOAD segments as (vaddr, file_off, filesz)."""
    e_phoff = struct.unpack_from('<I', d, 28)[0]
    e_phentsize = struct.unpack_from('<H', d, 42)[0]
    e_phnum = struct.unpack_from('<H', d, 44)[0]
    segs = []
    for i in range(e_phnum):
        o = e_phoff + i * e_phentsize
        p_type, p_offset, p_vaddr, _, p_filesz, _ = struct.unpack_from('<6I', d, o)
        if p_type == 1:
            segs.append((p_vaddr, p_offset, p_filesz))
    return segs


def vaddr_to_off(segs, va):
    for v, off, sz in segs:
        if v <= va < v + sz:
            return off + (va - v)
    return None


def find_reg_settings(d):
    """Return [(vaddr, count, file_off)] for every reg_setting struct."""
    segs = segments(d)
    # The library is a shared object linked at vaddr 0, so the values stored
    # in .data are the vaddrs of the arrays.
    out = []
    for off in range(0, len(d) - 16, 4):
        ptr, count, atype, dtype = struct.unpack_from('<4I', d, off)
        if not (1 <= count <= 512):
            continue
        if atype != ADDR_WORD or dtype != DATA_BYTE:
            continue
        foff = vaddr_to_off(segs, ptr)
        if foff is None or foff + count * 8 > len(d):
            continue
        # the array must look like register settings
        ok = True
        for i in range(count):
            addr, val, delay = struct.unpack_from('<HHI', d, foff + i * 8)
            if not (0x0000 <= addr <= 0x7FFF):
                ok = False
                break
        if ok:
            out.append((ptr, count, foff))
    # de-duplicate, keep the largest table per address
    best = {}
    for ptr, count, foff in out:
        if ptr not in best or count > best[ptr][0]:
            best[ptr] = (count, foff)
    return sorted((p, c, f) for p, (c, f) in best.items())


def main():
    lib, out = sys.argv[1], sys.argv[2]
    d = open(lib, 'rb').read()
    tables = find_reg_settings(d)
    if not tables:
        sys.exit("no register tables found in " + lib)

    lines = [
        "/*",
        " * IMX179 register settings.",
        " *",
        " * Generated by tools/gen-imx179-regs.py from the vendor sensor",
        " * library's IMX179 tables (register data only -- no vendor code).",
        " * The sensor driver in the kernel tree is a stub: it has the power",
        " * sequence but no mode tables, so the mode settings have to be",
        " * handed to the kernel by userspace (CFG_WRITE_I2C_ARRAY).",
        " *",
        " * Each entry is { uint16 reg_addr; uint16 reg_data; uint32 delay; },",
        " * the layout of struct msm_camera_i2c_reg_array.",
        " *",
        " * Do not edit by hand; regenerate instead.",
        " */",
        "",
        "#ifndef IMX179_REGS_H",
        "#define IMX179_REGS_H",
        "",
        "#include <stdint.h>",
        "",
        "struct imx179_reg {",
        "\tuint16_t addr;",
        "\tuint16_t data;",
        "\tuint32_t delay;",
        "};",
        "",
    ]
    for i, (vaddr, count, foff) in enumerate(tables):
        name = "imx179_settings_%d" % i
        lines.append("/* %d entries, library vaddr 0x%05x */" % (count, vaddr))
        lines.append("static const struct imx179_reg %s[%d] = {" % (name, count))
        for k in range(count):
            a, v, dl = struct.unpack_from('<HHI', d, foff + k * 8)
            lines.append("\t{ 0x%04x, 0x%02x, %d }," % (a, v, dl))
        lines.append("};")
        lines.append("")

    # The sensor's full-resolution mode is the one with the largest table.
    big = max(range(len(tables)), key=lambda i: tables[i][1])
    lines.append("/* the table to use: the sensor's full-resolution mode */")
    lines.append("#define IMX179_MODE_TABLE imx179_settings_%d" % big)
    lines.append("#define IMX179_MODE_TABLE_LEN %d" % tables[big][1])
    lines.append("")
    lines.append("#endif /* IMX179_REGS_H */")
    open(out, 'w').write('\n'.join(lines) + '\n')
    print("wrote %s: %d tables (%s), main one has %d entries"
          % (out, len(tables),
             ", ".join(str(t[1]) for t in tables), tables[big][1]))


if __name__ == '__main__':
    main()
