import _nfc, time
print("step 1: opening")
fd = _nfc.open()
print("  opened, fd =", fd)
print("step 2: the power cycle")
_nfc.wake(fd, 0); _nfc.power(fd, 0)
time.sleep(0.01)
_nfc.power(fd, 1)
_nfc.wake(fd, 0)
_nfc.wake(fd, 1)
print("step 3: reading the core reset")
p = _nfc.read(fd, 3000)
print("  got:", p)
print("step 4: GET_BUILD_INFO")
_nfc.write(fd, bytes([0x10, 0x2f, 0x04, 0x00]))
p = _nfc.read(fd, 3000)
print("  got:", p)
_nfc.power(fd, 0)
_nfc.close(fd)
print("done")
