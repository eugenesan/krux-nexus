#!/usr/bin/env python3
"""
gen-font.py -- generate a bitmap font for the standalone payload.

WHY THIS EXISTS

The result screen spent several runs hand-encoding values as bar counts:
"3 bars on top, 1 bar in the middle", "1 2 1 1". Every round produced a new
ambiguity -- a popcount mistaken for a count, a placeholder mistaken for an
errno, a hexdump mistaken for a step number. The encoding was the problem, not
the reader.

A 5x7 font costs 96 bytes for the glyphs actually needed and removes the entire
class of error: the screen can say "STEP 7  ERRNO 0" instead of making a human
reverse a visual code.

FONT SOURCE

Rasterised from a system TrueType face with Pillow rather than transcribed from
memory, which is the same mistake as writing 0x4321 instead of reading
include/linux/reboot.h. Generated, not recalled.

OUTPUT
    font5x7.h  -- a const table of 5-byte column-major glyphs

Each glyph is 5 columns; each column is a byte whose bit 0 is the TOP row of 7.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

CHARS = (
    " !\"#$%&'()*+,-./0123456789:;<=>?"
    "@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_"
)
GW, GH = 5, 7          # glyph cell, in pixels
PAD = 1                # spacing built into the cell
CELL_W, CELL_H = GW + PAD, GH + PAD


def find_font():
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
        "/usr/share/fonts/truetype/lato/Lato-Medium.ttf",
        "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf",
    ]
    for c in candidates:
        if os.path.exists(c):
            return c
    raise SystemExit("no usable TrueType font found")


def rasterise(fontpath, ch):
    """Render one character and return GW*GH bits, row-major, as a list."""
    best = None
    # Pick the pixel size that makes this glyph fill the 5x7 cell most
    # completely without clipping, rather than guessing a size once.
    for size in range(6, 16):
        font = ImageFont.truetype(fontpath, size)
        img = Image.new("1", (CELL_W + 4, CELL_H + 4), 0)
        d = ImageDraw.Draw(img)
        d.text((1, 0), ch, font=font, fill=1)
        px = img.load()
        w, h = img.size
        # crop to the glyph's ink
        xs, ys, xe, ye = w, h, 0, 0
        for y in range(h):
            for x in range(w):
                if px[x, y]:
                    xs, ys = min(xs, x), min(ys, y)
                    xe, ye = max(xe, x), max(ye, y)
        if xe < xs:
            continue
        gw, gh = xe - xs + 1, ye - ys + 1
        ink = sum(px[x, y] for y in range(ys, ye + 1) for x in range(xs, xe + 1))
        if gw > GW or gh > GH:
            continue
        fill = ink / float(gw * gh)
        # Prefer the LARGEST glyph that still fits the cell. Scoring on fill
        # ratio alone picks the smallest renderings, which came out only four
        # rows tall and hard to read. Height first, width second, fill last.
        key = (gh, gw, fill)
        if best is None or key > best[0]:
            best = (key, [[px[x, y] for x in range(xs, xe + 1)]
                          for y in range(ys, ye + 1)], gw, gh)
    if best is None:
        # blank glyph (space, or nothing renderable)
        return [[0] * GW for _ in range(GH)], 0
    _, grid, gw, gh = best
    # Normalise to exactly GW x GH. The rasteriser crops to the ink, so a
    # narrow glyph like '1' or 'I' comes back narrower than the cell; without
    # this the packer indexes off the end.
    norm = [[0] * GW for _ in range(GH)]
    for y in range(gh):
        for x in range(gw):
            if grid[y][x] and y < GH and x < GW:
                norm[y][x] = 1
    return norm, ink_of(norm)


def ink_of(grid):
    return sum(sum(r) for r in grid)


def pack(grid):
    """Row-major GH x GW bits -> GW column bytes, bit0 = top row."""
    cols = []
    for x in range(GW):
        v = 0
        for y in range(GH):
            if grid[y][x]:
                v |= (1 << y)
        cols.append(v)
    return cols


def main():
    fontpath = find_font()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font5x7.h")

    first = ord(CHARS[0])
    table = []
    for ch in CHARS:
        grid, ink = rasterise(fontpath, ch)
        table.append((ch, ink, pack(grid)))

    with open(out, "w") as f:
        f.write("/* Generated by gen-font.py -- do not edit.\n")
        f.write(" * Source face: %s\n" % fontpath)
        f.write(" * %d glyphs, ASCII %d..%d, %dx%d, column-major, bit0 = top row.\n"
                % (len(CHARS), first, first + len(CHARS) - 1, GW, GH))
        f.write(" * Layout per glyph: 5 bytes = 5 columns. */\n")
        f.write("#ifndef FONT5X7_H\n#define FONT5X7_H\n\n")
        f.write("#define FONT_FIRST %d\n" % first)
        f.write("#define FONT_GLYPH_W %d\n#define FONT_GLYPH_H %d\n" % (GW, GH))
        f.write("#define FONT_CELL_W  %d\n#define FONT_CELL_H  %d\n\n" % (CELL_W, CELL_H))
        f.write("static const unsigned char font5x7[][5] = {\n")
        for ch, ink, cols in table:
            disp = ch if ch not in ('\\',) else '\\\\'
            f.write("    { 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x }, /* %s */\n"
                    % (cols[0], cols[1], cols[2], cols[3], cols[4], disp))
        f.write("};\n\n#endif\n")

    print("  wrote %s (%d glyphs, %d bytes)"
          % (os.path.basename(out), len(CHARS), len(CHARS) * 5))

    # Visual proof that the glyphs are actually readable. Printed, not assumed.
    print("\n  preview (rendered back from the generated table):\n")
    sample = "STEP 7 ERRNO 0 NFC OK!"
    for y in range(GH):
        line = "    "
        for ch in sample:
            idx = ord(ch) - first
            cols = table[idx][2]
            for x in range(GW):
                line += "#" if cols[x] & (1 << y) else "."
            line += "."
        print(line)
    blanks = [ch for ch, ink, _ in table if ink == 0]
    print("\n  blank glyphs: %r" % ("".join(blanks) or "none"))


if __name__ == "__main__":
    main()